        <div class="purse-faq-accordion">
          <div class="faq-purse-item active">
            <button class="faq-purse-btn">Why is two-needle hand saddle stitching superior to sewing machine stitching? <span class="faq-toggle-icon">+</span></button>
            <div class="faq-purse-content">
              A sewing machine uses a lockstitch mechanism with two separate threads (top thread and bobbin thread) looped together in the center of the leather. If one thread breaks or wears through, the entire seam rapidly unravels. In contrast, a hand saddle stitch (Point Sellier) uses two needles on a single continuous strand of beeswaxed linen thread passed through each awl hole from opposite sides. Every stitch forms an independent figure-eight knot; even if a thread is cut, the seam remains firmly locked and will not unravel.
            </div>
          </div>
          <div class="faq-purse-item">
            <button class="faq-purse-btn">How does French Box Calf differ from Togo and Epsom leathers? <span class="faq-toggle-icon">+</span></button>
            <div class="faq-purse-content">
              French Box Calf is a smooth, full-grain calfskin hand-boarded to create subtle micro-grain; it holds crisp architectural shapes and develops a legendary glassy patina over decades. Togo is a natural shrunk calfskin with a supple, pebbled grain and exceptional scratch resilience. Epsom is an embossed-grain leather pressed with high heat and resin, creating a rigid, lightweight, completely scratch-resistant surface that does not show water spots.
            </div>
          </div>
          <div class="faq-purse-item">
            <button class="faq-purse-btn">What causes leather handbag corners to wear, and how are edges restored? <span class="faq-toggle-icon">+</span></button>
            <div class="faq-purse-content">
              Corner wear occurs when friction rubs away the protective edge paint and compresses the underlying leather grain. In our archival restoration salon, worn corners are cleaned, reshaped with grain filler, sanded smooth through micro-grit abrasives, and recoated with multiple layers of matching high-solid edge paint before hot iron beeswax filetage burnishing seals the edge against moisture.
            </div>
          </div>
          <div class="faq-purse-item">
            <button class="faq-purse-btn">What is the optimal climate condition for long-term luxury purse storage? <span class="faq-toggle-icon">+</span></button>
            <div class="faq-purse-content">
              Fine leather handbags must be stored in a climate-controlled environment between 65&deg;F and 72&deg;F (18&deg;C to 22&deg;C) with relative humidity strictly maintained between 45% and 55%. Lower humidity dries out natural leather oils, causing cracking, while higher humidity promotes mold growth. Bags should be stuffed with acid-free tissue paper to maintain silhouette shape and stored in breathable cotton dust covers away from direct sunlight.
            </div>
